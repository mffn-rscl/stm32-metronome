void draw_bpm_value(uint16_t bpm_val, uint8_t *framebuffer)
{
    uint8_t hundreds = (bpm_val / 100) % 10;
    uint8_t tens = (bpm_val / 10) % 10;  
    uint8_t units = bpm_val % 10;        


    uint16_t offset = (SSD1306_PAGE_VALUE * 128) + SSD1306_COL_VALUE;

    memcpy((void*)&framebuffer[offset],      font8x8_digits[hundreds], 8);
    memcpy((void*)&framebuffer[offset + 8],  font8x8_digits[tens],     8);
    memcpy((void*)&framebuffer[offset + 16], font8x8_digits[units],    8);
}


void draw_bpm_prefix(uint8_t *framebuffer)
{
    uint16_t offset = (SSD1306_PAGE_VALUE * 128) + SSD1306_COL_VALUE;

    memcpy((void*)&framebuffer[offset],      font8x8_bpm[0], 8); // 'B'
    memcpy((void*)&framebuffer[offset + 8],  font8x8_bpm[1], 8); // 'P'
    memcpy((void*)&framebuffer[offset + 16], font8x8_bpm[2], 8); // 'M'
    memcpy((void*)&framebuffer[offset + 24], font8x8_bpm[3], 8); // ':'
    memcpy((void*)&framebuffer[offset + 32], font8x8_bpm[4], 8); // ' '
}
